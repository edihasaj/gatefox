import { readFileSync, writeFileSync } from 'node:fs';
import { gatewaySdkLockRepairDigest, gatewaySdkPatchDigest, gatewaySdkSourceDigest } from './gateway-sdk-source.mjs';

// Derived hashes live outside the source digest, avoiding a self-referential receipt.
const path = 'src/gateway-sdk-build-pins.ts';
const text = `// Generated by scripts/sync-gateway-sdk-pins.mjs. Do not edit.\n` +
  `export const gatewaySdkPatchSha256 = "${gatewaySdkPatchDigest()}";\n` +
  `export const gatewaySdkLockRepairSha256 = "${gatewaySdkLockRepairDigest()}";\n` +
  `export const gatewaySdkSourceSha256 = "${gatewaySdkSourceDigest()}";\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== text) throw Error('Gateway SDK derived pins are stale; run npm run sdk:pins');
} else writeFileSync(path, text);
