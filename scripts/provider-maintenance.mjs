#!/usr/bin/env node
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, renameSync, unlinkSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';
import { discoverProviderReleases, officialBytes } from './provider-release-discovery.mjs';
import { sha256, writeSdkCandidate } from './provider-sdk-candidate.mjs';
import { runValidation, validationEnvironment } from './provider-maintenance-process.mjs';
import { safeValidationMetadata } from './provider-maintenance-diagnostics.mjs';
import { validateProviderCli } from './validate-provider-cli.mjs';
import { withPrivateFileLock } from '../dist/private-file-lock.js';
import { promoteProviderTools } from './promote-provider-tools.mjs';

export const promotedFiles = ['src/gateway-sdk-pin.json', 'src/gateway-sdk-build-pins.ts',
  'src/gateway-feature-schema-data.json', 'src/provider-tool-contract.ts', 'provider-compatibility.json'];
const git = (root, args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
const atomicJson = (path, value) => {
  const stage = `${path}.next`; writeFileSync(stage, JSON.stringify(value, null, 2) + '\n', { mode: 0o600 });
  renameSync(stage, path);
};
const readJson = path => { try { return JSON.parse(readFileSync(path, 'utf8')); } catch { return undefined; } };
const journalPath = root => join(root, '.state/provider-maintenance/promotion.json');
const fileHash = path => existsSync(path) ? sha256(readFileSync(path)) : null;

/** Keep Rust package paths stable across candidates. The builder still checks the entire immutable source tree. */
function sdkBuildDirectory(root, pin) {
  const state = join(root, '.state/provider-maintenance');
  const previous = readdirSync(state).filter(name => name.startsWith('candidate-')).map(name =>
    join(state, name, 'checkout/.state/gateway-sdk-build'));
  for (const directory of [join(state, 'sdk-build'), ...previous]) {
    const receipt = readJson(join(directory, 'artifact/build.json'));
    if (receipt?.revision === pin.revision && receipt.archiveSha256 === pin.archiveSha256 && receipt.profile === 'release') return directory;
  }
  return join(state, 'sdk-build');
}

/** Recover only our exact generated bytes after a crash; any intervening edit keeps its files and asks for inspection. */
export function recoverSourcePromotion(root) {
  const path = journalPath(root); if (!existsSync(path)) return;
  const journal = readJson(path);
  if (journal?.schemaVersion !== 1 || !/^[a-f0-9]{40}$/.test(journal.base) ||
    JSON.stringify(Object.keys(journal.files ?? {}).sort()) !== JSON.stringify([...promotedFiles].sort())) throw Error('Provider promotion journal needs inspection');
  const head = git(root, ['rev-parse', 'HEAD']);
  const allAfter = promotedFiles.every(name => fileHash(join(root, name)) === journal.files[name].after);
  if (head !== journal.base) {
    // A committed, fully promoted update survived; no source rollback belongs after its commit.
    if (allAfter && git(root, ['rev-parse', 'HEAD^']) === journal.base) { unlinkSync(path); return; }
    throw Error('Source changed during provider promotion; journal retained');
  }
  for (const name of promotedFiles) {
    const entry = journal.files[name];
    if (!/^[a-f0-9]{64}$/.test(entry.after) || (entry.before !== null && (typeof entry.before !== 'string' || entry.before.length > 2 * 1024 * 1024))) throw Error('Invalid provider promotion journal');
    const current = fileHash(join(root, name)); const before = entry.before === null ? null : sha256(Buffer.from(entry.before, 'base64'));
    if (current !== entry.after && current !== before) throw Error('Generated source changed during provider promotion; files preserved');
  }
  for (const name of promotedFiles) {
    const before = journal.files[name].before;
    if (before === null) { if (existsSync(join(root, name))) unlinkSync(join(root, name)); }
    else writeFileSync(join(root, name), Buffer.from(before, 'base64'));
  }
  unlinkSync(path);
}

export async function candidateEvidence(candidate, expected) {
  const files = Object.fromEntries([...promotedFiles, 'dist/provider-tool-runtime.js', 'dist/provider-tool-contract.js',
    'gateway-sdk/build.json', 'gateway-sdk/gateway-codex']
    .map(path => [path, sha256(readFileSync(join(candidate, path)))]));
  if (expected && JSON.stringify(files) !== JSON.stringify(expected.files)) throw Error('Verified candidate changed');
  const { providerToolTree } = await import(pathToFileURL(join(candidate, 'dist/provider-tool-runtime.js')));
  return { files, cli: Object.fromEntries(await Promise.all(['claude', 'copilot'].map(async kind =>
    [kind, await providerToolTree(join(dirname(candidate), kind, 'node_modules'))]))) };
}

/** Refuse a stale candidate or somebody else's in-progress work before touching a source file. */
export function applyCandidate(root, candidate, base, { retainJournal = false } = {}) {
  if (git(root, ['rev-parse', 'HEAD']) !== base || git(root, ['status', '--porcelain'])) throw Error('Source changed; verified candidate was retained');
  const next = new Map(promotedFiles.map(path => [path, readFileSync(join(candidate, path))]));
  const original = new Map(promotedFiles.map(path => [path, existsSync(join(root, path)) ? readFileSync(join(root, path)) : undefined]));
  const journal = journalPath(root); mkdirSync(dirname(journal), { recursive: true, mode: 0o700 });
  atomicJson(journal, { schemaVersion: 1, base, files: Object.fromEntries(promotedFiles.map(path =>
    [path, { before: original.get(path)?.toString('base64') ?? null, after: sha256(next.get(path)) }])) });
  try {
    for (const [index, path] of promotedFiles.entries()) {
      const stage = join(dirname(journal), `promotion-${index}.next`);
      writeFileSync(stage, next.get(path), { mode: 0o600 });
      renameSync(stage, join(root, path));
    }
    if (!retainJournal) unlinkSync(journal);
  } catch {
    recoverSourcePromotion(root);
    throw Error('Provider update promotion failed; previous pins restored');
  }
}

export async function maintainProviders(options = {}) {
  const root = resolve(options.root ?? fileURLToPath(new URL('..', import.meta.url)));
  const state = join(root, '.state/provider-maintenance'); mkdirSync(state, { recursive: true, mode: 0o700 });
  try { return await withPrivateFileLock(join(state, 'running'), () => {
    recoverSourcePromotion(root); return maintainLocked({ ...options, root });
  }, 100); }
  catch (error) { if (error.code === 'ELOCKBUSY') throw Error('Provider maintenance already running'); throw error; }
}

async function maintainLocked({ root, apply = false, allowDirty = false,
  commit = false, branch, discover = discoverProviderReleases, validateCli = validateProviderCli, run = runValidation,
  promoteTools = promoteProviderTools } = {}) {
  root = resolve(root);
  if (commit && !apply) throw Error('Committing provider pins requires --apply');
  const state = join(root, '.state/provider-maintenance'); mkdirSync(state, { recursive: true, mode: 0o700 });
  const report = { schemaVersion: 1, checkedAt: new Date().toISOString(), status: 'blocked', phase: 'source' };
  const save = () => {
    atomicJson(join(state, 'latest.json'), report);
  };
  const promote = async candidate => {
    if (JSON.stringify(await candidateEvidence(candidate, report.evidence)) !== JSON.stringify(report.evidence)) throw Error('Verified candidate changed');
    applyCandidate(root, candidate, report.base, { retainJournal: true });
    await promoteTools(dirname(candidate), report.releases);
    report.status = 'applied';
    if (commit && git(root, ['status', '--porcelain'])) {
      // The helper stages only these generated files. Nothing else can enter the commit.
      execFileSync('committer', ['chore: advance verified stable provider tools', ...promotedFiles],
        { cwd: root, stdio: ['ignore', 'pipe', 'pipe'], timeout: 30_000 });
      report.base = git(root, ['rev-parse', 'HEAD']);
      report.status = 'current';
    }
    unlinkSync(journalPath(root));
  };
  try {
    const base = git(root, ['rev-parse', 'HEAD']); report.base = base; report.preflight = allowDirty;
    if (branch && git(root, ['symbolic-ref', '--short', 'HEAD']) !== branch) throw Error('Scheduled provider maintenance branch changed');
    if (git(root, ['status', '--porcelain']) && (!allowDirty || apply)) throw Error('Provider maintenance requires clean source');
    report.phase = 'discovery'; const releases = await discover(); report.releases = releases;
    const previous = readJson(join(state, 'verified.json'));
    let intact = false;
    if (previous?.evidence && typeof previous.candidate === 'string' && previous.candidate.startsWith(`${state}/candidate-`)) {
      try { intact = JSON.stringify(await candidateEvidence(previous.candidate, previous.evidence)) === JSON.stringify(previous.evidence); } catch {}
    }
    if (!allowDirty && previous?.base === base && !previous.preflight && JSON.stringify(previous.releases) === JSON.stringify(releases) && intact) {
      Object.assign(report, previous, { checkedAt: report.checkedAt, status: 'verified', phase: 'complete' });
      if (apply) { await promote(previous.candidate); atomicJson(join(state, 'verified.json'), report); }
      save(); return report;
    }
    const directory = mkdtempSync(join(state, 'candidate-')); report.candidate = join(directory, 'checkout');
    const checkout = report.candidate; mkdirSync(checkout, { mode: 0o700 });
    // Copy only version-controlled source; never .state, credentials, provider homes or previous build output.
    for (const path of git(root, ['ls-files', '-z']).split('\0').filter(Boolean)) {
      if (path.startsWith('.state/') || !existsSync(join(root, path))) continue;
      mkdirSync(dirname(join(checkout, path)), { recursive: true, mode: 0o700 }); cpSync(join(root, path), join(checkout, path));
    }
    const env = validationEnvironment(join(directory, 'home'), {
      RUSTUP_HOME: process.env.RUSTUP_HOME ?? join(homedir(), '.rustup'),
      CARGO_HOME: process.env.CARGO_HOME ?? join(homedir(), '.cargo'), RUST_MIN_STACK: '33554432',
    });
    const step = async (phase, command, args, options = {}) => {
      report.phase = phase; save();
      return run(command, args, { cwd: checkout, env, ...options });
    };
    report.phase = 'codex_source'; save();
    const bytes = await officialBytes(`https://codeload.github.com/openai/codex/legacy.tar.gz/${releases.codex.revision}`, 64 * 1024 * 1024);
    const archive = join(directory, 'codex.tar.gz'); writeFileSync(archive, bytes, { mode: 0o600 });
    const source = join(directory, 'codex-source'); mkdirSync(source, { mode: 0o700 });
    await run('tar', ['-xzf', archive, '--strip-components=1', '-C', source], { cwd: directory, env });
    const pin = writeSdkCandidate(checkout, source, releases.codex, sha256(bytes));
    const sdkBuildRoot = sdkBuildDirectory(root, pin);
    await step('pins', process.execPath, ['scripts/sync-gateway-sdk-pins.mjs']);
    await step('dependencies', 'npm', ['ci', '--ignore-scripts', '--no-audit', '--no-fund'], { timeoutMs: 300_000 });
    await step('build', 'npm', ['run', 'build']);
    const qualification = { schemaVersion: 1, codex: releases.codex };
    for (const kind of ['claude', 'copilot']) {
      report.phase = kind; save();
      qualification[kind] = await validateCli(kind, releases[kind], join(directory, kind), checkout);
    }
    writeFileSync(join(checkout, 'provider-compatibility.json'), JSON.stringify(qualification, null, 2) + '\n');
    await step('typecheck', 'npm', ['run', 'check']);
    await step('tests', 'npm', ['test'], { timeoutMs: 600_000, maximumOutput: 16 * 1024 * 1024 });
    await step('maintenance_tests', process.execPath, ['--test', ...readdirSync(join(checkout, 'scripts/tests'))
      .filter(name => /^provider-.*\.test\.mjs$/.test(name)).sort().map(name => `scripts/tests/${name}`)]);
    await step('sdk_tests', process.execPath, ['scripts/build-gateway-sdk.mjs', '--test', '--dev', '--archive', archive,
      '--build-root', sdkBuildRoot, '--target-dir', join(root, '.state/gateway-sdk-build/target')], { timeoutMs: 3_600_000, maximumOutput: 64 * 1024 * 1024 });
    await step('sdk_build', process.execPath, ['scripts/build-gateway-sdk.mjs', '--archive', archive,
      '--build-root', sdkBuildRoot, '--target-dir', join(root, '.state/gateway-sdk-build/target')], { timeoutMs: 3_600_000, maximumOutput: 64 * 1024 * 1024 });
    cpSync(join(sdkBuildRoot, 'artifact'), join(checkout, 'gateway-sdk'), { recursive: true });
    await step('sdk_gateway_e2e', process.execPath, ['scripts/e2e-identity.mjs', '--package', checkout,
      '--root', join(directory, 'sdk-e2e')], { timeoutMs: 300_000 });
    // Native gate receipts and a release-profile executable are both required before pins can advance.
    report.evidence = await candidateEvidence(checkout);
    report.phase = 'complete'; report.status = 'verified'; save();
    atomicJson(join(state, 'verified.json'), report);
    if (apply) { await promote(checkout); atomicJson(join(state, 'verified.json'), report); save(); }
    return report;
  } catch (error) {
    recoverSourcePromotion(root);
    Object.assign(report, safeValidationMetadata(error, report.candidate));
    report.status = 'blocked'; save();
    throw Error(`Provider maintenance blocked at ${report.phase}; last verified pins and running processes were preserved`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { values } = parseArgs({ options: { apply: { type: 'boolean' }, commit: { type: 'boolean' }, branch: { type: 'string' }, 'allow-dirty': { type: 'boolean' } } });
  maintainProviders({ apply: values.apply, commit: values.commit, branch: values.branch, allowDirty: values['allow-dirty'] }).then(report => {
    console.log(JSON.stringify({ status: report.status, phase: report.phase, versions: Object.fromEntries(Object.entries(report.releases).map(([key, value]) => [key, value.version])) }));
  }).catch(error => { console.error(error.message); process.exitCode = 1; });
}
